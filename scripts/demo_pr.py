#!/usr/bin/env python3
"""Replay the life of a pull request against a scratch copy of this repo.

  1. main                - every rule passes
  2. PR, commit 1        - someone "simplifies" the encoded-PowerShell rule
  3. PR, commit 2        - a typo in a field name slips in while fixing it
  4. PR, commit 3        - the real fix; the gate goes green again

Each step runs the same `sigmaforge ci` the GitHub workflow runs, against the
baseline main would have committed. Use it for the README GIF, or pass
`--write-doc docs/example-pr.md` to regenerate the walkthrough from real output.

    python scripts/demo_pr.py [--equivalence] [--write-doc docs/example-pr.md]
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULE = "rules/windows/process_creation/proc_creation_win_powershell_encoded_cmd.yml"

STEPS = [
    (
        "PR commit 1 - \"simplify the encoded-command patterns, drop the SCCM filter\"",
        [
            ("      - ' -e '\n      - ' -en '\n      - ' -enc '\n      - ' -ec '\n      - ' -encodedcommand '\n",
             "      - ' -e'\n"),
            ("  filter_sccm:\n    ParentImage: 'C:\\Windows\\CCM\\CcmExec.exe'\n", ""),
            ("  condition: all of selection_* and not filter_sccm", "  condition: all of selection_*"),
        ],
    ),
    (
        "PR commit 2 - \"restore the patterns\" (with a typo in the field name)",
        [
            ("      - ' -e'\n", "      - ' -e '\n      - ' -en '\n      - ' -enc '\n      - ' -ec '\n      - ' -encodedcommand '\n"),
            ("  condition: all of selection_*", "  filter_sccm:\n    ParentImage: 'C:\\Windows\\CCM\\CcmExec.exe'\n  condition: all of selection_* and not filter_sccm"),
            ("    CommandLine|windash|contains:", "    CommandLne|windash|contains:"),
        ],
    ),
    (
        "PR commit 3 - \"fix field name\"",
        [("    CommandLne|windash|contains:", "    CommandLine|windash|contains:")],
    ),
]


def sh(cmd: list[str], cwd: Path) -> tuple[int, str]:
    env = {**os.environ, "NO_COLOR": "1"}
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env)
    return proc.returncode, proc.stdout + proc.stderr


def gate_summary(work: Path) -> str:
    gate = json.loads((work / "out/gate.json").read_text())
    lines = [f"decision: {gate['decision'].upper()}"]
    lines += [f"  BLOCK  {r}" for r in gate["reasons"]]
    lines += [f"  warn   {w}" for w in gate["warnings"]]
    lines += [f"  +      {i}" for i in gate["improvements"]]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--equivalence", action="store_true", help="include cross-backend replay (slower)")
    ap.add_argument("--write-doc", help="write a Markdown walkthrough with the captured output")
    args = ap.parse_args()
    exe = shutil.which("sigmaforge") or str(Path(sys.executable).parent / "sigmaforge")
    ci = [exe, "ci"] + ([] if args.equivalence else ["--no-equivalence"])

    work = Path(tempfile.mkdtemp(prefix="sigmaforge-demo-"))
    for name in ("rules", "tests", "datasets", "baseline", "sigmaforge.yml", "equivalence-exceptions.yml"):
        src = ROOT / name
        (shutil.copytree if src.is_dir() else shutil.copy)(src, work / name)
    if (ROOT / ".cache").exists():
        (work / ".cache").symlink_to(ROOT / ".cache")
    record: list[tuple[str, str, str]] = []

    print("== main: build the baseline main would commit")
    code, out = sh([exe, "baseline", "update"], work)
    code, out = sh(ci, work)
    print(gate_summary(work))
    record.append(("main", "", gate_summary(work)))

    for title, edits in STEPS:
        path = work / RULE
        before = path.read_text()
        text = before
        for old, new in edits:
            assert old in text, old
            text = text.replace(old, new, 1)
        path.write_text(text)
        diff = "".join(difflib.unified_diff(before.splitlines(True), text.splitlines(True), f"a/{RULE}", f"b/{RULE}", n=1))
        print(f"\n== {title}\n{diff}")
        code, out = sh(ci, work)
        summary = gate_summary(work)
        print(summary)
        record.append((title, diff, summary))

    if args.write_doc:
        write_doc(Path(args.write_doc), record, work)
        print(f"\nwrote {args.write_doc}")
    shutil.rmtree(work, ignore_errors=True)
    return 0


def write_doc(path: Path, record: list[tuple[str, str, str]], work: Path) -> None:
    lines = [
        "# Example PR: a broken rule caught and fixed",
        "",
        "Generated by `python scripts/demo_pr.py --write-doc docs/example-pr.md`: every block below is",
        "real output of the same `sigmaforge ci` command the GitHub workflow runs on a pull request,",
        "compared against the baseline `main` commits.",
        "",
    ]
    for title, diff, summary in record:
        lines.append(f"## {title}")
        lines.append("")
        if diff:
            lines += ["```diff", diff.rstrip(), "```", ""]
        lines += ["Gate output:", "", "```text", summary, "```", ""]
    lines += [
        "## What each block shows",
        "",
        "* **Commit 1** drops the trailing space from `' -e'` and removes the SCCM filter. The rule still",
        "  fires on every labelled positive, so a TPR-only test would pass. It now also matches",
        "  `-ExecutionPolicy`, `-Encoding` and every Configuration Manager script, so it fires on the",
        "  near-miss negatives and blows its noise budget on the benign baseline.",
        "* **Commit 2** restores the patterns but misspells `CommandLine`. Sigma accepts any field name,",
        "  so the rule is still valid YAML and still converts. The selection now matches nothing, so",
        "  the true-positive rate drops to 0%, the real EVTX sample stops firing, and T1059.001",
        "  disappears from the coverage map. The gate reports both the rule failure and the coverage",
        "  regression against `main`.",
        "* **Commit 3** fixes the field name and the gate is green again.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
